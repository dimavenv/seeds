// Транслитерация названия сорта в человекочитаемый слаг:
// «Томат Бычье сердце» → «tomat-byche-serdce».
//
// Слаг — это часть адреса карточки (/product/<slug>), поэтому название сорта
// в нём латиницей: и покупателю понятно, что за ссылку ему прислали, и
// ключевое слово попадает в URL. Кириллица в адресе превратилась бы в
// нечитаемый процент-энкодинг вида %D1%82%D0%BE...
//
// Живёт отдельным модулем (а не внутри админских server actions), потому что
// нужен ещё и скрипту backfill: scripts/pb-backfill-slugs.mjs. Правила там
// продублированы намеренно — .mjs-скрипт запускается без сборщика и не может
// импортировать TypeScript; при изменении таблицы правьте оба места.

const TRANSLIT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh",
  з: "z", и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o",
  п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "ts",
  ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu",
  я: "ya",
};

export function slugify(input: string): string {
  return input
    .toLowerCase()
    .split("")
    .map((ch) => TRANSLIT[ch] ?? ch)
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    // Обрезка по 60 символам могла оставить дефис на конце — убираем повторно.
    .replace(/-+$/g, "");
}
